# Portable Redis 5 control (for the BullMQ submission queue, the OTP store and
# the visitor-tracking salt). Usage:
#   pwsh scripts/redis.ps1 start | stop | status | register | unregister
#
# SERVICE-AWARE, exactly as scripts/db.ps1 became for Postgres: when the service
# exists this drives the service, and when it does not it falls back to starting
# the binary directly — so it behaves the same either side of registration and
# nothing that calls it has to know which.
#
# WHY REGISTRATION EXISTS. Redis went down on 2026-11-06 and took the OTP store
# with it, because a console-started process dies with its console and does not
# come back after a reboot. Postgres had the identical failure three times in one
# day before it was registered as `investoyard-postgres`. `start-services.bat`
# still works; this removes the need to remember it.
#
# LIVENESS IS `redis-cli ping`, NEVER THE PORT AND NEVER THE SERVICE STATE.
# An orphaned process keeps the listening socket, so an open port is exactly what
# a wedged Redis looks like — the same reason `start-services.bat` once reported
# Postgres UP while it refused every query. And a service can report Running over
# a Redis that answers nothing, which is the `pg_ctl status` lie in different
# clothes. PONG is the only answer that means anything.
param([string]$cmd = 'status')

$root = Split-Path $PSScriptRoot -Parent
$bin  = Join-Path $root '.tools\redis\redis-server.exe'
$cli  = Join-Path $root '.tools\redis\redis-cli.exe'
$data = Join-Path $root '.redisdata'
$port = 6379
$svc  = 'investoyard-redis'   # mirrors investoyard-postgres

# The conf the SERVICE reads. GENERATED from $port and $data rather than
# hand-written or taken from the shipped redis.windows-service.conf, and that is
# the point: the console path passes those values as flags, so a separate conf
# would be a second place for them to live and the two start paths would
# eventually disagree about the port, the directory or — worse — persistence.
# The shipped conf enables RDB snapshots; this Redis is a pure cache and must
# stay one, or registering it would quietly turn it into a store we would then
# have to back up.
$conf = Join-Path $data 'redis-service.conf'

function Test-Elevated {
  $id = [Security.Principal.WindowsIdentity]::GetCurrent()
  return (New-Object Security.Principal.WindowsPrincipal($id)).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Get-RedisService {
  # -ErrorAction SilentlyContinue suppresses the OUTPUT but still makes this
  # script exit 1, so the absence of a service has to be caught, not ignored.
  try { return Get-Service -Name $svc -ErrorAction Stop } catch { return $null }
}

function Test-RedisUp {
  $ping = (& $cli -p $port ping 2>$null)
  return ($ping -match 'PONG')
}

function Wait-RedisUp([int]$seconds = 15) {
  for ($i = 0; $i -lt $seconds; $i++) {
    if (Test-RedisUp) { return $true }
    Start-Sleep -Seconds 1
  }
  return $false
}

function Write-ServiceConf {
  New-Item -ItemType Directory -Force $data | Out-Null
  # `dir` must be the data directory and the path is quoted for spaces.
  # `save ""` with an EMPTY argument list is how RDB snapshots are disabled in a
  # conf file — it is the file-form of the console `--save ""`.
  # FORWARD SLASHES, AND THIS IS NOT COSMETIC. Inside a double-quoted conf
  # value Redis processes backslash ESCAPES, and `\U` / `\f` are not escapes it
  # knows — so it drops the backslash and "D:\Investoyard\.redisdata" arrives as
  # `D:Investoyard.redisdata`. Measured: Redis refused to start with
  # "Can't chdir to 'C:UsersfinwaveAppData...'". Windows accepts forward slashes
  # in a path, and Redis passes them through untouched. The quotes stay, for a
  # path with spaces.
  $dirConf = $data.Replace('\', '/')
  $lines = @(
    '# GENERATED by scripts/redis.ps1 register. Do not hand-edit:',
    '# re-running register overwrites it, and the console start path reads the',
    '# same values as flags, so editing one here would split them in two.',
    "port $port",
    "dir `"$dirConf`"",
    'save ""',
    'appendonly no',
    # NO `bind` LINE, DELIBERATELY, and it is not an oversight. The console
    # start passes no bind either, so Redis listens on 0.0.0.0 AND [::], and the
    # API connects over IPv6 loopback — `netstat` shows an ESTABLISHED
    # `[::1]:6379`, because `localhost` resolves to `::1` first on this box (the
    # same resolver order that once made the web build fetch a different
    # application on port 3000). `bind 127.0.0.1` would therefore REFUSE the
    # API's own connection. Redis 5 has no optional-bind syntax (`-::1` is 6+),
    # so a bind line naming both stacks would also make Redis refuse to start on
    # a host without IPv6. `protected-mode yes` is what limits exposure, and it
    # is the default. Tightening this to loopback-only is a security decision
    # for the operator, not something to change by registering a service.
    'protected-mode yes'
  )
  # ASCII, NOT utf8: Set-Content -Encoding utf8 writes a BOM in PowerShell 5.1,
  # and Redis would read those three bytes as part of the first directive and
  # refuse to start. (The default is the ANSI codepage, which is also wrong.)
  Set-Content -Path $conf -Value $lines -Encoding ascii
}

switch ($cmd) {

  'start' {
    if (Test-RedisUp) { Write-Host "redis already up on :$port"; break }
    $s = Get-RedisService
    if ($s) {
      Write-Host "starting the $svc service..."
      try { Start-Service -Name $svc -ErrorAction Stop } catch { Write-Host "Start-Service failed: $($_.Exception.Message)"; break }
    } else {
      if (-not (Test-Path $bin)) { Write-Host 'Portable Redis not found under .tools\redis'; break }
      New-Item -ItemType Directory -Force $data | Out-Null
      Start-Process -FilePath $bin -ArgumentList "--port $port --dir `"$data`" --save `"`" --appendonly no" -WindowStyle Hidden
    }
    if (Wait-RedisUp) { Write-Host "redis up on :$port (PONG)" } else { Write-Host "redis did NOT answer on :$port" }
  }

  'stop' {
    $s = Get-RedisService
    if ($s) {
      # Needs elevation, like every other service control here.
      if (-not (Test-Elevated)) { Write-Host "redis runs as the $svc service - stopping it needs an ELEVATED shell."; break }
      try { Stop-Service -Name $svc -Force -ErrorAction Stop; Write-Host "$svc stopped" } catch { Write-Host "Stop-Service failed: $($_.Exception.Message)" }
    } else {
      & $cli -p $port shutdown nosave 2>$null
      Write-Host 'redis stopped'
    }
  }

  'register' {
    # ELEVATION IS CHECKED FIRST, BEFORE ANYTHING IS TOUCHED, so a refusal costs
    # nothing — the same ordering db.ps1 uses, and the reason a failed register
    # there never left Postgres down.
    if (-not (Test-Elevated)) {
      Write-Host 'register needs an ELEVATED shell (SeCreateServicePrivilege). Nothing was changed.'
      Write-Host 'Run PowerShell as Administrator, then: pwsh scripts\redis.ps1 register'
      break
    }
    if (Get-RedisService) { Write-Host "$svc is already registered. Nothing to do."; break }
    if (-not (Test-Path $bin)) { Write-Host 'Portable Redis not found under .tools\redis'; break }

    # Say what the handover costs before doing it. There is NO persistence
    # configured, so the keyspace is a cache: the BullMQ queue metadata is
    # recreated by the API on its next connection, an unconsumed OTP is lost
    # (the investor requests another), and the visitor salt rotates a few hours
    # early. Worth stating rather than discovering.
    $keys = (& $cli -p $port dbsize 2>$null)
    if ($keys) { Write-Host "redis currently holds $keys key(s); it has no persistence configured, so they are dropped by the handover." }

    Write-ServiceConf
    Write-Host "wrote $conf"

    if (Test-RedisUp) {
      Write-Host 'stopping the console instance so the service can take :6379...'
      & $cli -p $port shutdown nosave 2>$null
      Start-Sleep -Seconds 2
    }

    Write-Host "installing $svc..."
    & $bin --service-install $conf --service-name $svc
    if (-not (Get-RedisService)) { Write-Host 'service-install did not create the service. Nothing is running - start it with: pwsh scripts\redis.ps1 start'; break }

    # Automatic start, so it survives a reboot - which is the whole point.
    try { Set-Service -Name $svc -StartupType Automatic -ErrorAction Stop } catch { Write-Host "could not set Automatic start: $($_.Exception.Message)" }

    # Restart-on-failure 5s / 10s / 30s, matching investoyard-postgres.
    # `sc.exe`, NOT `sc`: bare `sc` is PowerShell's alias for Set-Content, and
    # the spaces after `reset=` and `actions=` are required by sc.exe's parser.
    & sc.exe failure $svc reset= 86400 actions= restart/5000/restart/10000/restart/30000 | Out-Null

    try { Start-Service -Name $svc -ErrorAction Stop } catch { Write-Host "Start-Service failed: $($_.Exception.Message)" }
    if (Wait-RedisUp) {
      Write-Host "$svc registered and up on :$port (PONG). It now starts on boot."
    } else {
      Write-Host "$svc registered but Redis is NOT answering on :$port - check the Windows event log (source: $svc)."
    }
  }

  'unregister' {
    if (-not (Test-Elevated)) {
      Write-Host 'unregister needs an ELEVATED shell (SeCreateServicePrivilege). Nothing was changed.'
      break
    }
    if (-not (Get-RedisService)) { Write-Host "$svc is not registered. Nothing to do."; break }
    try { Stop-Service -Name $svc -Force -ErrorAction Stop } catch { Write-Host "Stop-Service: $($_.Exception.Message)" }
    & $bin --service-uninstall --service-name $svc
    if (Get-RedisService) {
      Write-Host "$svc still present - service-uninstall may need a reboot to complete."
    } else {
      Write-Host "$svc unregistered. `start` now launches the console instance again."
    }
  }

  default {
    # `(if ...)` is not an expression in PowerShell 5.1 - it parses, then fails
    # at runtime. Needs the subexpression form.
    $up = Test-RedisUp
    $s  = Get-RedisService
    Write-Host $(if ($up) { "redis up on :$port (PONG)" } else { "redis not answering on :$port" })
    if ($s) {
      Write-Host ("service    : $svc - " + $s.Status + ", startup " + $s.StartType)
      # A service reported Running over a Redis that answers nothing is the
      # state worth naming, because every other signal looks healthy.
      if (($s.Status -eq 'Running') -and (-not $up)) {
        Write-Host 'WARNING    : the service is Running but Redis is not answering - treat it as DOWN.'
      }
    } else {
      Write-Host "service    : not registered (console instance; will not survive a reboot)"
      Write-Host "             register it with an ELEVATED: pwsh scripts\redis.ps1 register"
    }
  }
}
