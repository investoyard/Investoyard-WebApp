// Scaffolds fall back to English until translated.
const dicts: Record<Lang, Dict> = { en, hi, ta: {}, te: {}, bn: {}, mr: {} };

export function t(lang: Lang, key: string): string {
  return dicts[lang]?.[key] ?? en[key] ?? key;
}

/** Bind a language once: const tr = makeT(lang); tr('home.title') */
export function makeT(lang: Lang) {
  return (key: string) => t(lang, key);
}

